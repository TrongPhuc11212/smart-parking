create table if not exists public.staff_activity_logs (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  actor_id uuid references public.staff_profiles(user_id) on delete set null,
  actor_email text not null,
  actor_name text not null,
  action text not null check (action in ('CHECK_IN', 'CHECK_OUT')),
  ticket_code text not null,
  license_plate text not null,
  slot_code text not null,
  amount numeric,
  payment_reference uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists staff_activity_logs_created_idx
  on public.staff_activity_logs (created_at desc, id desc);
create index if not exists staff_activity_logs_actor_created_idx
  on public.staff_activity_logs (actor_id, created_at desc);
create index if not exists staff_activity_logs_action_created_idx
  on public.staff_activity_logs (action, created_at desc);

alter table public.staff_activity_logs enable row level security;
revoke all on public.staff_activity_logs from public, anon, authenticated;
grant select, insert on public.staff_activity_logs to service_role;
grant usage, select on sequence public.staff_activity_logs_id_seq to service_role;

create or replace function public.check_in_vehicle_with_activity(
  p_license_plate text,
  p_slot_id bigint,
  p_actor_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
  v_ticket jsonb;
  v_actor public.staff_profiles%rowtype;
  v_slot_code text;
begin
  select *
  into v_actor
  from public.staff_profiles
  where user_id = p_actor_id
    and is_active;

  if not found then
    return jsonb_build_object(
      'success', false,
      'code', 'actor_not_staff',
      'message', 'Tài khoản nhân viên không hợp lệ hoặc đã bị khóa.'
    );
  end if;

  v_result := public.check_in_vehicle(p_license_plate, p_slot_id);
  if not coalesce((v_result ->> 'success')::boolean, false) then
    return v_result;
  end if;

  v_ticket := v_result -> 'ticket';
  select slot_code
  into v_slot_code
  from public.parking_slots
  where id = (v_ticket ->> 'slot_id')::bigint;

  insert into public.staff_activity_logs (
    event_key,
    actor_id,
    actor_email,
    actor_name,
    action,
    ticket_code,
    license_plate,
    slot_code,
    details
  )
  values (
    'CHECK_IN:' || (v_ticket ->> 'ticket_code'),
    v_actor.user_id,
    v_actor.email,
    v_actor.full_name,
    'CHECK_IN',
    v_ticket ->> 'ticket_code',
    v_ticket ->> 'license_plate',
    coalesce(v_slot_code, p_slot_id::text),
    jsonb_build_object('slotId', p_slot_id)
  )
  on conflict (event_key) do nothing;

  return v_result;
end;
$$;

create or replace function public.check_out_vehicle_with_activity(
  p_license_plate text,
  p_payment_reference uuid,
  p_actor_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result jsonb;
  v_receipt jsonb;
  v_actor public.staff_profiles%rowtype;
begin
  select *
  into v_actor
  from public.staff_profiles
  where user_id = p_actor_id
    and is_active;

  if not found then
    return jsonb_build_object(
      'success', false,
      'code', 'actor_not_staff',
      'message', 'Tài khoản nhân viên không hợp lệ hoặc đã bị khóa.'
    );
  end if;

  v_result := public.check_out_vehicle(p_license_plate, p_payment_reference);
  if not coalesce((v_result ->> 'success')::boolean, false) then
    return v_result;
  end if;

  v_receipt := v_result -> 'receipt';
  if v_receipt ->> 'paymentStatus' = 'PENDING' then
    insert into public.staff_activity_logs (
      event_key,
      actor_id,
      actor_email,
      actor_name,
      action,
      ticket_code,
      license_plate,
      slot_code,
      amount,
      payment_reference,
      details
    )
    values (
      'CHECK_OUT:' || (v_receipt ->> 'paymentReference'),
      v_actor.user_id,
      v_actor.email,
      v_actor.full_name,
      'CHECK_OUT',
      v_receipt ->> 'ticketCode',
      v_receipt ->> 'licensePlate',
      v_receipt ->> 'slotCode',
      (v_receipt ->> 'amount')::numeric,
      (v_receipt ->> 'paymentReference')::uuid,
      jsonb_build_object(
        'paymentCode', v_receipt ->> 'paymentCode',
        'paymentStatus', v_receipt ->> 'paymentStatus'
      )
    )
    on conflict (event_key) do nothing;
  end if;

  return v_result;
end;
$$;

revoke all on function public.check_in_vehicle_with_activity(text, bigint, uuid)
  from public, anon, authenticated;
revoke all on function public.check_out_vehicle_with_activity(text, uuid, uuid)
  from public, anon, authenticated;
grant execute on function public.check_in_vehicle_with_activity(text, bigint, uuid)
  to service_role;
grant execute on function public.check_out_vehicle_with_activity(text, uuid, uuid)
  to service_role;

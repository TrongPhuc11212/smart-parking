create table if not exists public.manager_activity_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.staff_profiles(user_id) on delete set null,
  actor_email text not null,
  actor_name text not null,
  action text not null check (
    action in (
      'STAFF_CREATED',
      'STAFF_UPDATED',
      'PARKING_RATE_UPDATED',
      'INVOICE_CANCELLED',
      'INVOICE_COMPLETED_MANUALLY'
    )
  ),
  target_type text not null,
  target_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists manager_activity_logs_created_idx
  on public.manager_activity_logs (created_at desc, id desc);
create index if not exists manager_activity_logs_action_created_idx
  on public.manager_activity_logs (action, created_at desc);

alter table public.manager_activity_logs enable row level security;
revoke all on public.manager_activity_logs from public, anon, authenticated;
grant select, insert on public.manager_activity_logs to service_role;
grant usage, select on sequence public.manager_activity_logs_id_seq to service_role;

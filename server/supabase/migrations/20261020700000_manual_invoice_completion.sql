alter table public.tickets
  add column if not exists settlement_method text
    check (settlement_method in ('SEPAY', 'MANUAL'));

create table if not exists public.parking_invoice_manual_completions (
  id bigint generated by default as identity primary key,
  ticket_code text not null,
  license_plate text not null,
  payment_reference uuid,
  payment_code text,
  amount numeric not null,
  reason text not null,
  completed_by uuid not null references public.staff_profiles(user_id),
  completed_at timestamptz not null default now()
);

create index if not exists parking_invoice_manual_completions_ticket_idx
  on public.parking_invoice_manual_completions (ticket_code, completed_at desc);

alter table public.parking_invoice_manual_completions enable row level security;
revoke all on public.parking_invoice_manual_completions
  from public, anon, authenticated;
grant select, insert on public.parking_invoice_manual_completions to service_role;
grant usage, select
  on sequence public.parking_invoice_manual_completions_id_seq
  to service_role;

create or replace function public.complete_parking_invoice_manually(
  p_actor_id uuid,
  p_ticket_code text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ticket public.tickets%rowtype;
  v_slot public.parking_slots%rowtype;
  v_reason text := btrim(coalesce(p_reason, ''));
  v_completed_at timestamptz;
begin
  if not exists (
    select 1
    from public.staff_profiles
    where user_id = p_actor_id
      and role = 'MANAGER'
      and is_active
  ) then
    return jsonb_build_object(
      'success', false,
      'code', 'actor_not_manager',
      'message', 'Chỉ quản lý đang hoạt động mới được hoàn tất hóa đơn thủ công.'
    );
  end if;

  if p_ticket_code is null or btrim(p_ticket_code) = ''
    or length(btrim(coalesce(p_reason, ''))) < 3
    or length(v_reason) > 500 then
    return jsonb_build_object(
      'success', false,
      'code', 'invalid_request',
      'message', 'Mã vé hoặc lý do hoàn tất không hợp lệ.'
    );
  end if;

  select *
  into v_ticket
  from public.tickets
  where ticket_code = btrim(p_ticket_code)
  for update;

  if not found then
    return jsonb_build_object(
      'success', false,
      'code', 'ticket_not_found',
      'message', 'Không tìm thấy vé gửi xe.'
    );
  end if;

  if v_ticket.status <> 'ACTIVE' or v_ticket.payment_status <> 'PENDING' then
    return jsonb_build_object(
      'success', false,
      'code', 'invoice_not_pending',
      'message', 'Chỉ hóa đơn đang chờ thanh toán của xe còn trong bãi mới được hoàn tất.'
    );
  end if;

  select *
  into v_slot
  from public.parking_slots
  where id = v_ticket.slot_id
  for update;

  if not found then
    return jsonb_build_object(
      'success', false,
      'code', 'slot_not_found',
      'message', 'Không tìm thấy vị trí đỗ của vé.'
    );
  end if;

  insert into public.parking_invoice_manual_completions (
    ticket_code,
    license_plate,
    payment_reference,
    payment_code,
    amount,
    reason,
    completed_by
  )
  values (
    v_ticket.ticket_code,
    v_ticket.license_plate,
    v_ticket.payment_reference,
    v_ticket.payment_code,
    v_ticket.total_amount,
    v_reason,
    p_actor_id
  )
  returning completed_at into v_completed_at;

  update public.tickets
  set status = 'COMPLETED',
      payment_status = 'PAID',
      settlement_method = 'MANUAL'
  where id = v_ticket.id
    and status = 'ACTIVE'
    and payment_status = 'PENDING';

  if not found then
    raise exception 'Vé % đã được xử lý đồng thời.', v_ticket.ticket_code;
  end if;

  update public.parking_slots
  set status = 'AVAILABLE'
  where id = v_ticket.slot_id;

  return jsonb_build_object(
    'success', true,
    'ticketCode', v_ticket.ticket_code,
    'licensePlate', v_ticket.license_plate,
    'paymentStatus', 'PAID',
    'settlementMethod', 'MANUAL',
    'completedBy', p_actor_id,
    'amount', v_ticket.total_amount,
    'completedAt', v_completed_at,
    'slotCode', v_slot.slot_code,
    'reason', v_reason
  );
end;
$$;

revoke all on function public.complete_parking_invoice_manually(uuid, text, text)
  from public, anon, authenticated;
grant execute on function public.complete_parking_invoice_manually(uuid, text, text)
  to service_role;

create or replace function public.confirm_sepay_payment(
  p_sepay_transaction_id bigint,
  p_payment_code text,
  p_amount numeric,
  p_account_number text
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  v_ticket public.tickets%rowtype;
begin
  if p_sepay_transaction_id is null or p_sepay_transaction_id <= 0
    or p_payment_code is null or p_amount is null or p_amount <= 0
    or p_account_number is null then
    return jsonb_build_object('success', false, 'code', 'invalid_transaction');
  end if;

  if exists (
    select 1
    from public.tickets
    where sepay_transaction_id = p_sepay_transaction_id
      and payment_status = 'PAID'
  ) then
    return jsonb_build_object('success', true, 'duplicate', true);
  end if;

  select *
  into v_ticket
  from public.tickets
  where payment_code = upper(p_payment_code)
    and status = 'ACTIVE'
    and payment_status = 'PENDING'
  for update;

  if not found then
    return jsonb_build_object('success', false, 'code', 'payment_not_found');
  end if;

  if p_amount <> v_ticket.total_amount then
    return jsonb_build_object('success', false, 'code', 'amount_mismatch');
  end if;

  update public.tickets
  set payment_status = 'PAID',
      settlement_method = 'SEPAY',
      sepay_transaction_id = p_sepay_transaction_id,
      status = 'COMPLETED'
  where id = v_ticket.id
    and payment_status = 'PENDING';

  if not found then
    return jsonb_build_object('success', false, 'code', 'payment_already_processed');
  end if;

  update public.parking_slots
  set status = 'AVAILABLE'
  where id = v_ticket.slot_id;

  return jsonb_build_object('success', true, 'duplicate', false);
end;
$$;

revoke all on function public.confirm_sepay_payment(bigint, text, numeric, text)
  from public, anon, authenticated;
grant execute on function public.confirm_sepay_payment(bigint, text, numeric, text)
  to service_role;

create table if not exists public.parking_invoice_cancellations (
  id bigint generated by default as identity primary key,
  ticket_code text not null,
  license_plate text not null,
  payment_reference uuid,
  payment_code text,
  amount numeric not null,
  cancelled_by uuid not null references public.staff_profiles(user_id),
  cancelled_at timestamptz not null default now()
);

create index if not exists parking_invoice_cancellations_ticket_idx
  on public.parking_invoice_cancellations (ticket_code, cancelled_at desc);

alter table public.parking_invoice_cancellations enable row level security;
revoke all on public.parking_invoice_cancellations from public, anon, authenticated;
grant select, insert on public.parking_invoice_cancellations to service_role;
grant usage, select
  on sequence public.parking_invoice_cancellations_id_seq
  to service_role;

create or replace function public.cancel_pending_parking_invoice(
  p_actor_id uuid,
  p_ticket_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ticket public.tickets%rowtype;
  v_cancelled_at timestamptz;
begin
  if not exists (
    select 1
    from public.staff_profiles
    where user_id = p_actor_id
      and role = 'MANAGER'
      and is_active
  ) then
    return jsonb_build_object(
      'success', false,
      'code', 'actor_not_manager',
      'message', 'Chỉ quản lý đang hoạt động mới được hủy hóa đơn.'
    );
  end if;

  if p_ticket_code is null or btrim(p_ticket_code) = '' then
    return jsonb_build_object(
      'success', false,
      'code', 'invalid_ticket',
      'message', 'Mã vé không hợp lệ.'
    );
  end if;

  select *
  into v_ticket
  from public.tickets
  where ticket_code = btrim(p_ticket_code)
  for update;

  if not found then
    return jsonb_build_object(
      'success', false,
      'code', 'ticket_not_found',
      'message', 'Không tìm thấy vé gửi xe.'
    );
  end if;

  if v_ticket.status <> 'ACTIVE' or v_ticket.payment_status <> 'PENDING' then
    return jsonb_build_object(
      'success', false,
      'code', 'invoice_not_pending',
      'message', 'Chỉ có thể hủy hóa đơn đang chờ thanh toán.'
    );
  end if;

  insert into public.parking_invoice_cancellations (
    ticket_code,
    license_plate,
    payment_reference,
    payment_code,
    amount,
    cancelled_by
  )
  values (
    v_ticket.ticket_code,
    v_ticket.license_plate,
    v_ticket.payment_reference,
    v_ticket.payment_code,
    v_ticket.total_amount,
    p_actor_id
  )
  returning cancelled_at into v_cancelled_at;

  update public.tickets
  set payment_status = 'CANCELLED',
      payment_reference = null,
      payment_code = null,
      sepay_transaction_id = null
  where id = v_ticket.id;

  return jsonb_build_object(
    'success', true,
    'ticketCode', v_ticket.ticket_code,
    'licensePlate', v_ticket.license_plate,
    'paymentStatus', 'CANCELLED',
    'cancellation', jsonb_build_object(
      'payment_code', v_ticket.payment_code,
      'amount', v_ticket.total_amount,
      'cancelled_at', v_cancelled_at
    )
  );
end;
$$;

revoke all on function public.cancel_pending_parking_invoice(uuid, text)
  from public, anon, authenticated;
grant execute on function public.cancel_pending_parking_invoice(uuid, text)
  to service_role;

create or replace function public.get_parking_revenue_report(
  p_from_date date,
  p_to_date date
)
returns table (
  report_date date,
  checkout_tickets bigint,
  paid_tickets bigint,
  paid_revenue numeric,
  pending_tickets bigint,
  pending_amount numeric
)
language sql
stable
set search_path = public
as $$
  select
    (tickets.check_out_time at time zone 'Asia/Ho_Chi_Minh')::date as report_date,
    count(*) filter (where tickets.payment_status <> 'CANCELLED')::bigint
      as checkout_tickets,
    count(*) filter (where tickets.payment_status = 'PAID')::bigint as paid_tickets,
    coalesce(
      sum(tickets.total_amount) filter (where tickets.payment_status = 'PAID'),
      0
    )::numeric as paid_revenue,
    count(*) filter (where tickets.payment_status = 'PENDING')::bigint
      as pending_tickets,
    coalesce(
      sum(tickets.total_amount) filter (where tickets.payment_status = 'PENDING'),
      0
    )::numeric as pending_amount
  from public.tickets
  where tickets.check_out_time >=
      (p_from_date::timestamp at time zone 'Asia/Ho_Chi_Minh')
    and tickets.check_out_time <
      ((p_to_date + 1)::timestamp at time zone 'Asia/Ho_Chi_Minh')
  group by (tickets.check_out_time at time zone 'Asia/Ho_Chi_Minh')::date
  order by report_date;
$$;

revoke all on function public.get_parking_revenue_report(date, date)
  from public, anon, authenticated;
grant execute on function public.get_parking_revenue_report(date, date)
  to service_role;
